def band(colors):
    im = Image.new('RGBA', (W_, H_)); d = ImageDraw.Draw(im); n = len(colors)
    for i, (col, w) in enumerate(colors): pass
    y = 0; tot = sum(w for _, w in colors)
    for col, w in colors:
        h = round(H_ * w / tot); d.rectangle([0, y, W_, y + h], fill=col); y += h
    return im, d
def pack(im):
    if mask: im.putalpha(mask)
    b = io.BytesIO(); im.save(b, 'PNG'); return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()
